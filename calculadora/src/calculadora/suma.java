public class suma {
     // Método 1: dos enteros
    public int sumar(int a, int b) {
        return a + b;
    }

    // Método 2: tres enteros
    public int sumar(int a, int b, int c) {
        return a + b + c;
    }

    // Método 3: dos double
    public double sumar(double a, double b) {
        return a + b;
    }
}
  

